//! Contrato del escenario aislado; no registra comandos IPC ni endpoints HTTP.

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

/// Identificador del runner de pruebas; no es un comando Tauri registrado.
pub const LAB_COMMAND: &str = "lab.runScenario";

/// Códigos públicos del adaptador de laboratorio; no equivalen a errores HTTP Java.
#[derive(Clone, Copy, Debug, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum LabErrorCode {
    /// Respuesta incompatible con el contrato generado.
    InvalidLabResponse,
    /// Falló el proceso aislado; no se publica el error interno.
    LabScenarioFailed,
}

trait ContractType {
    const TYPESCRIPT: &'static str;
    const JSON_TYPE: &'static str;
}

impl ContractType for String {
    const TYPESCRIPT: &'static str = "string";
    const JSON_TYPE: &'static str = "string";
}

impl ContractType for bool {
    const TYPESCRIPT: &'static str = "boolean";
    const JSON_TYPE: &'static str = "boolean";
}

// Una sola lista define los campos serializados, sus tipos TS y el esquema.
macro_rules! report_contract {
    ($($field:ident: $rust:ty => $wire:literal),+ $(,)?) => {
        /// Resultado público del escenario sintético, sin credenciales ni sesiones.
        #[derive(Debug, Serialize, Deserialize)]
        #[serde(rename_all = "camelCase", deny_unknown_fields)]
        pub struct ScenarioReport {
            $(#[doc = concat!("Campo de contrato `", $wire, "`.")]
            #[serde(rename = $wire)]
            pub $field: $rust,)+
        }

        /// Genera TypeScript y JSON Schema desde la misma definición Rust.
        pub fn bindings() -> String {
            let mut ts = String::from("// Generated by pos-lab --export-contract. DO NOT EDIT.\nexport interface ScenarioReport {\n");
            $(ts.push_str(&format!("  {}: {};\n", $wire, <$rust as ContractType>::TYPESCRIPT));)+
            ts.push_str("}\nexport const scenarioReportSchema = ");
            let schema = json!({
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "title": "ScenarioReport", "type": "object", "additionalProperties": false,
                "required": [$($wire),+],
                "properties": {$($wire: {"type": <$rust as ContractType>::JSON_TYPE}),+}
            });
            ts.push_str(&schema.to_string());
            ts.push_str(" as const;\n");
            ts.push_str(&format!("export const labCommand = {} as const;\n", json!(LAB_COMMAND)));
            let codes = json!([LabErrorCode::InvalidLabResponse, LabErrorCode::LabScenarioFailed]);
            ts.push_str(&format!("export const labErrorCodes = {codes} as const;\n"));
            ts.push_str("export type LabErrorCode = typeof labErrorCodes[number];\nexport interface LabError { code: LabErrorCode }\n");
            ts
        }
    };
}

report_contract! {
    productive: bool => "productive",
    scope: String => "scope",
    sale_id: String => "saleId",
    sale_total: String => "saleTotal",
    change_amount: String => "changeAmount",
    sale_status: String => "saleStatus",
    cash_shift_status: String => "cashShiftStatus",
    inventory_balance: String => "inventoryBalance",
    open_sale_prevented_close: bool => "openSalePreventedClose",
}

impl ScenarioReport {
    /// Traduce y valida el informe interno después de reabrir SQLite.
    pub fn from_internal(report: &Value) -> Result<Self, &'static str> {
        let text = |value: &Value| {
            value
                .as_str()
                .map(str::to_owned)
                .ok_or("informe incompleto")
        };
        let result = Self {
            productive: false,
            scope: "synthetic_sqlite_candidate_schema".into(),
            sale_id: text(&report["sale_id"])?,
            sale_total: text(&report["sale_total"])?,
            change_amount: text(&report["change_amount"])?,
            sale_status: text(&report["reopen"]["sale_status"])?,
            cash_shift_status: text(&report["reopen"]["cash_shift_status"])?,
            inventory_balance: text(&report["reopen"]["inventory_balance"])?,
            open_sale_prevented_close: report["closed_while_sale_open"] == false,
        };
        if result.sale_status != "COMPLETED"
            || result.cash_shift_status != "CLOSED"
            || !result.open_sale_prevented_close
            || report["reopen"]["payments"] != 1
            || report["reopen"]["audit_events"].as_i64().unwrap_or(0) < 11
        {
            return Err("invariantes del escenario incumplidas");
        }
        Ok(result)
    }
}

